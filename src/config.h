// -----------------------------------------------------------------------------
//  Wi-Fi はここに「初期値」を直書きしておけます。
//  実機ではキーボードから設定し直せて、その内容は本体(NVS)に保存されます。
//  → 保存済み設定があればそちらが優先。無ければ下の初期値で接続を試みます。
