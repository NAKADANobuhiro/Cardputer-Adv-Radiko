// =============================================================================
//  config.h - ビルド時の初期設定
// -----------------------------------------------------------------------------
//  Wi-Fi はここに「初期値」を直書きしておけます。
//  実機ではキーボードから設定し直せて、その内容は本体(NVS)に保存されます。
//  → 保存済み設定があればそちらが優先。無ければ下の初期値で接続を試みます。
// =============================================================================
#pragma once

// ----- Wi-Fi 初期値（空文字ならスキップし、実機のセットアップ画面へ誘導）-----
#define WIFI_SSID_DEFAULT     ""     // 例: "my-home-wifi"
#define WIFI_PASS_DEFAULT     ""     // 例: "password1234"

// ----- 地域 / 初期選局 -----
//  神奈川県(JP14)想定。エリアは接続元IPで自動判定されるので通常は表示用。
#define RADIKO_AREA_ID        "JP14"     // 神奈川県（既定/表示用）
#define DEFAULT_STATION_INDEX 0          // stations.h の並びで TBS を先頭(=0)に
//  実機の A キーで選んだエリアの局リストは本体(NVS)に保存され次回以降そちらを使う。
#define MAX_STATIONS          40         // 動的取得する局リストの上限

// ----- 時計(NTP) -----
#define NTP_SERVER1           "ntp.nict.jp"       // 日本標準時
#define NTP_SERVER2           "time.google.com"
#define JST_OFFSET_SEC        (9 * 3600)          // JST = UTC+9

// ----- 現在番組名の再取得間隔 -----
#define PROG_REFRESH_MS       300000    // 成功後は5分ごとに now.xml から番組名を更新
#define PROG_RETRY_MS         20000     // 取得失敗時は20秒後に再試行(「取得中」放置を防ぐ)

// ----- 充電/給電(CHG)判定のしきい値 -----
//  Cardputer ADV は充電信号線が無く電池をADC電圧分圧で読むだけのため、充電の直接検出は不可。
//  代わりに電圧が高い(=USB給電/満充電付近)ときを "CHG" とみなす。
//  実測: 再生中の電池駆動≈3.75V / USB給電時≈4.2V。しきい値はその中間の少し上に置く。
#define BAT_CHG_MV            4100      // これ以上(mV)なら CHG(給電/満充電付近)表示

// ----- 音量（UIは0-15レベル。実際のM5音量 = レベル×16, レベル6=96）-----
#define VOLUME_DEFAULT        6      // 0-15。6 → M5音量96相当
#define VOLUME_MAX            15
#define VOLUME_TO_M5(lv)      ((lv) * 16)   // レベル→M5 Speaker音量(0-255)

// ----- 省電力（無操作でバックライト消灯）-----
#define SCREEN_OFF_MS     60000    // 無操作でこの時間経過→バックライト消灯（音は継続）
#define DISPLAY_BRIGHTNESS 80      // 通常時の明るさ(0-255)

// ----- 再生バッファ関連の調整値（実機で微調整）-----
//  1回のネット読み出しサイズ。小さいほど応答が良く、大きいほど効率的。
#define NET_READ_CHUNK        1024
//  スピーカーのキューに溜め込む上限（大きいほど途切れにくいがRAM/遅延増）。
//  実機で音が途切れる→増やす / RAM不足で落ちる→減らす。
#define SPK_QUEUE_LIMIT       6

// ----- デバッグ出力 -----
#define LOG(...)   do { Serial.printf(__VA_ARGS__); } while (0)
